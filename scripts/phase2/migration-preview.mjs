#!/usr/bin/env node
// Dry run of the Phase 2 migration: prints what WOULD change, without touching any record.
//   node scripts/phase2/migration-preview.mjs > docs/PHASE2-MIGRATION-PREVIEW.md
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSources } from '../lib/atlas-data.mjs';
import { PROPOSED } from './proposed-mapping.mjs';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const tax = (f) => JSON.parse(readFileSync(join(ROOT, 'data/taxonomy/proposed', f), 'utf8'));
const types = tax('resource-types.json').items;
const domains = tax('knowledge-domains.json').items.flatMap((d) => d.children.map((c) => ({ ...c, parent: d })));
const caps = tax('capabilities.json').items;
const src = loadSources(ROOT);

export function resourceTypeFor(kind) {
  const t = types.find((x) => x.fromKind.includes(kind));
  if (!t) throw new Error(`No resource type for kind "${kind}"`);
  return t.id;
}

// Source type rule: official-documentation only when the source host equals the record's official host.
// Everything else stays `unclassified` for human review — no guessing.
export function sourceTypeFor(record, url) {
  try {
    const off = record.links.official && new URL(record.links.official).host;
    return off && new URL(url).host === off ? 'official-documentation' : 'unclassified';
  } catch { return 'unclassified'; }
}

const rows = src.ontologies.map(({ record: r }) => {
  const p = PROPOSED[r.id];
  const d = domains.find((x) => x.id === p.domain);
  const srcTypes = r.verification.sources.map((s) => sourceTypeFor(r, s.url));
  return { r, p, d, type: resourceTypeFor(r.kind), official: srcTypes.filter((t) => t !== 'unclassified').length, total: srcTypes.length };
});

const capLabel = Object.fromEntries(caps.map((c) => [c.id, c.label]));
const byType = rows.reduce((m, x) => ((m[x.type] = (m[x.type] || 0) + 1), m), {});
const tentative = rows.filter((x) => x.p.fit === 'tentative').length;
const official = rows.reduce((n, x) => n + x.official, 0);
const total = rows.reduce((n, x) => n + x.total, 0);

console.log(`# Phase 2 migration preview (dry run)

Generated by \`scripts/phase2/migration-preview.mjs\`. **No record has been changed.** This table is the editorial
proposal to review before the migration runs. See [PHASE2-ARCHITECTURE.md](PHASE2-ARCHITECTURE.md).

- Records: **${rows.length}**, all in the default *Ontologies & semantic models* family.
- Resource types (derived from the existing \`kind\`): ${Object.entries(byType).map(([k, v]) => `${k} ${v}`).join(' · ')}
- Knowledge-domain fit: ${rows.length - tentative} clear · **${tentative} tentative** (please confirm)
- Verification sources auto-typed as *official documentation*: ${official} of ${total}. The other ${total - official} stay \`unclassified\` until reviewed.
- Licence review status for all records: \`not-assessed\`. Commercial reuse: \`unknown\`.

| Record | Resource type | Knowledge domain → sub-domain | Fit | Engineering capabilities |
| --- | --- | --- | --- | --- |`);
for (const x of rows.sort((a, b) => a.r.name.localeCompare(b.r.name))) {
  console.log(`| ${x.r.name} (\`${x.r.id}\`) | ${x.type} | ${x.d.parent.label} → ${x.d.label} | ${x.p.fit === 'tentative' ? '**tentative**' : 'clear'} | ${x.p.capabilities.map((c) => capLabel[c]).join(', ')} |`);
}
